-- Monthly legal payroll-rate verification, with no write access to payroll itself.
CREATE TABLE IF NOT EXISTS public.college_payroll_rate_checks (
  month text PRIMARY KEY CHECK (month ~ '^20[0-9]{2}-(0[1-9]|1[0-2])$'),
  checked_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL CHECK (status IN ('verified','review','incomplete')),
  categories jsonb NOT NULL DEFAULT '{}'::jsonb,
  messages jsonb NOT NULL DEFAULT '{}'::jsonb,
  source_urls jsonb NOT NULL DEFAULT '{}'::jsonb
);
ALTER TABLE public.college_payroll_rate_checks ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.college_payroll_rate_checks FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.college_payroll_rate_checks TO service_role;

CREATE TABLE IF NOT EXISTS public.college_payroll_official_rate_snapshots (
  year integer NOT NULL CHECK (year BETWEEN 2026 AND 2100),
  category text NOT NULL CHECK (category IN ('navigo','repas','logement','vehicule','ntic')),
  payload jsonb NOT NULL,
  source_url text NOT NULL CHECK (source_url LIKE 'https://%'),
  effective_from text NOT NULL,
  checked_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (year,category)
);
ALTER TABLE public.college_payroll_official_rate_snapshots ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.college_payroll_official_rate_snapshots FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.college_payroll_official_rate_snapshots TO service_role;

CREATE TABLE IF NOT EXISTS public.college_payroll_rate_check_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month text NOT NULL CHECK (month ~ '^20[0-9]{2}-(0[1-9]|1[0-2])$'),
  started_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL CHECK (status IN ('verified','review','incomplete')),
  details jsonb NOT NULL DEFAULT '{}'::jsonb
);
ALTER TABLE public.college_payroll_rate_check_runs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.college_payroll_rate_check_runs FROM anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.college_payroll_rate_check_runs TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.college_payroll_rate_check_runs_id_seq TO service_role;

-- Generate the token entirely in Vault; neither JS source nor SQL job embeds its value.
SELECT vault.create_secret(
 replace(gen_random_uuid()::text,'-','') || replace(gen_random_uuid()::text,'-',''),
 'college_payroll_rates_cron_token_v1',
 'Monthly official-payroll-rate verification'
) WHERE NOT EXISTS (
 SELECT 1 FROM vault.decrypted_secrets WHERE name='college_payroll_rates_cron_token_v1'
);

CREATE OR REPLACE FUNCTION public.college_verify_rates_cron_token(p_token text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,public,vault AS $$
 SELECT length(p_token)=64 AND EXISTS (
  SELECT 1 FROM vault.decrypted_secrets
  WHERE name='college_payroll_rates_cron_token_v1'
    AND decrypted_secret=p_token
 );
$$;
REVOKE ALL ON FUNCTION public.college_verify_rates_cron_token(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.college_verify_rates_cron_token(text) TO service_role;
